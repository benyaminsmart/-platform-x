def _table(headers: list[str], rows: list[list]) -> str:
    if not rows:
        return '<p style="color:#6b7280; font-size:12.5px;">No data for this period.</p>'
    head = "<tr>" + "".join(f"<th>{h}</th>" for h in headers) + "</tr>"
    body = ""
    for i, r in enumerate(rows):
        cls = ' class="row-alt"' if i % 2 == 1 else ""
        body += f"<tr{cls}>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>"
    return f"<table><thead>{head}</thead><tbody>{body}</tbody></table>"


@limiter.limit("30/minute")
@router.get("/print", response_class=HTMLResponse)
def business_report_print(
    request: Request,
    days: int = Query(default=30, ge=1, le=3650),
    user: User = Depends(get_current_business_user),
    tenant: Tenant = Depends(get_business_tenant),
    db: DBSession = Depends(get_db),
) -> HTMLResponse:
    from_d = date.today() - timedelta(days=days)
    cfg = tenant.config or {}

    # KPIs
    total_bookings = (
        db.query(func.count(Booking.id))
        .filter(Booking.tenant_id == tenant.id, Booking.check_in >= from_d)
        .scalar() or 0
    )
    paid_rows = (
        db.query(Booking)
        .filter(
            Booking.tenant_id == tenant.id,
            Booking.check_in >= from_d,
            Booking.payment_status == "paid",
            Booking.status.notin_(_EXCLUDED),
        )
        .all()
    )
    revenue = sum(float(b.total_amount or 0) for b in paid_rows)
    avg_booking = round(revenue / len(paid_rows), 2) if paid_rows else 0.0

    # Top services
    top_svc = (
        db.query(Booking.service_name, func.count(Booking.id).label("cnt"))
        .filter(Booking.tenant_id == tenant.id, Booking.check_in >= from_d)
        .group_by(Booking.service_name)
        .order_by(func.count(Booking.id).desc())
        .limit(5)
        .all()
    )
    top_services_table = _table(
        ["Service", "Bookings"],
        [[r[0], r[1]] for r in top_svc],
    )

    # Top customers
    top_cust_rows = (
        db.query(Booking.user_id, func.count(Booking.id).label("cnt"),
                 func.coalesce(func.sum(Booking.total_amount), 0).label("total"))
        .filter(Booking.tenant_id == tenant.id, Booking.check_in >= from_d,
                Booking.status.notin_(_EXCLUDED))
        .group_by(Booking.user_id)
        .order_by(func.count(Booking.id).desc())
        .limit(5)
        .all()
    )
    user_ids = [r[0] for r in top_cust_rows]
    users = {u.id: u for u in db.query(User).filter(User.id.in_(user_ids)).all()} if user_ids else {}
    top_customers_table = _table(
        ["Customer", "Bookings", "Total (AED)"],
        [
            [f"{(users[r[0]].first_name or '')} {(users[r[0]].last_name or '')}".strip() if r[0] in users else "—",
             int(r[1]), str(r[2])]
            for r in top_cust_rows
        ],
    )

    # Recent bookings
    recent = (
        db.query(Booking)
        .filter(Booking.tenant_id == tenant.id, Booking.check_in >= from_d)
        .order_by(Booking.check_in.desc())
        .limit(10)
        .all()
    )
    recent_table = _table(
        ["Date", "Service", "Guests", "Total", "Status"],
        [[str(b.check_in), b.service_name, b.guests, f"{b.total_amount} {b.currency}", b.status] for b in recent],
    )

    from datetime import datetime, timezone
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    html = _REPORT_HTML.format(
        tenant_name=tenant.name,
        location=cfg.get("location") or "",
        period_days=days,
        generated_at=now,
        total_bookings=total_bookings,
        paid_bookings=len(paid_rows),
        revenue=round(revenue, 2),
        avg_booking=avg_booking,
        top_services_table=top_services_table,
        top_customers_table=top_customers_table,
        recent_table=recent_table,
    )
    return HTMLResponse(content=html)
